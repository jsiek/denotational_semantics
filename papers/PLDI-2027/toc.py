#!/usr/bin/env python3
"""The table of contents of loc.md, with Obsidian heading links.

Run from the repository root:  python3 papers/PLDI-2027/toc.py [file]

Rewrites, in place, the table of contents between the markers
<!-- toc --> and <!-- /toc --> (inserted after the title if missing): one
entry per ## and ### heading, nested by level, as Obsidian wikilinks
[[#Heading]].  Converts the links to headings in the GitHub form
[text](#github-anchor) to Obsidian's [[#Heading|text]] ([[#Heading\\|text]]
inside a table row, where a bare | would end the cell).  Then checks that
every heading link names a heading exactly and that no heading has a
character that Obsidian cannot link (# | ^ [ ]); it fails otherwise.
loc.py does not write loc.md, so the table of contents is regenerated by
running this script after editing the headings.
"""
import re, sys

PATH = sys.argv[1] if len(sys.argv) > 1 else 'papers/PLDI-2027/loc.md'
START, END = '<!-- toc -->', '<!-- /toc -->'


def headings(lines):
    """The (level, text) of the headings, outside fenced code blocks."""
    out, fence = [], False
    for line in lines:
        if line.startswith('```'):
            fence = not fence
        m = None if fence else re.match(r'(#{1,6}) (.*?)\s*$', line)
        if m:
            out.append((len(m.group(1)), m.group(2)))
    return out


def github_anchor(text):
    """The anchor GitHub gives a heading."""
    s = text.strip().lower()
    s = re.sub(r'[^\w\- ]', '', s)
    return s.replace(' ', '-')


def main():
    text = open(PATH, encoding='utf-8').read()
    lines = text.split('\n')
    hs = headings(lines)
    names = {h for _, h in hs}
    bad = [h for h in names if re.search(r'[#|^\[\]]', h)]
    if bad:
        sys.exit('headings that Obsidian cannot link: ' + ', '.join(bad))
    if len(names) != len(hs):
        dup = sorted({h for _, h in hs if [x for _, x in hs].count(h) > 1})
        sys.exit('headings that are not unique: ' + ', '.join(dup))

    # the GitHub links to headings, as Obsidian links
    anchors = {github_anchor(h): h for h in names}

    def convert(line):
        in_table = line.lstrip().startswith('|')

        def sub(m):
            label, anchor = m.group(1), m.group(2)
            if anchor not in anchors:
                sys.exit(f'link to no heading: {m.group(0)}')
            h = anchors[anchor]
            if label == h:
                return f'[[#{h}]]'
            return f'[[#{h}\\|{label}]]' if in_table else f'[[#{h}|{label}]]'
        return re.sub(r'\[([^\]]+)\]\(#([^)]+)\)', sub, line)
    lines = [convert(line) for line in lines]

    # the table of contents
    toc = [START, '']
    for level, h in hs:
        if level in (2, 3):
            toc.append('  ' * (level - 2) + f'- [[#{h}]]')
    toc += ['', END]
    if START in lines:
        i, j = lines.index(START), lines.index(END)
        lines[i:j + 1] = toc
    else:
        t = next(k for k, line in enumerate(lines) if line.startswith('# '))
        lines[t + 1:t + 1] = [''] + toc
    out = '\n'.join(lines)

    # every heading link names a heading
    for m in re.finditer(r'\[\[#([^\]|\\]+)(?:\\?\|[^\]]*)?\]\]', out):
        if m.group(1) not in names:
            sys.exit(f'link to no heading: {m.group(0)}')
    if re.search(r'\]\(#', out):
        sys.exit('a GitHub-style heading link is left')
    open(PATH, 'w', encoding='utf-8').write(out)


if __name__ == '__main__':
    main()
